public class AddTwoNumbers {
    public static void main(String[] args) {
        // Declare two numbers
        int number1 = 10;
        int number2 = 20;
        
        // Add the two numbers
        int sum = number1 + number2;
        
        // Display the result
        System.out.println("Number 1: " + number1);
        System.out.println("Number 2: " + number2);
        System.out.println("Sum: " + sum);
    }
}
